/**
 * Naomi's type scale.
 *
 * The Stitch reference specifies Inter. Naomi does not bundle it and uses
 * `FontFamily.SansSerif` — Roboto on virtually every Android device — which is
 * a deliberate trade, not an oversight: bundling four Inter weights costs
 * roughly a megabyte in an APK that is currently two, for a difference most
 * people would not name if asked.
 *
 * What actually carries the design is this scale: the sizes, the weights, and
 * the negative tracking on the large styles. That survives the substitution.
 * If Inter is ever added, drop the files in `res/font/` and change the family
 * here — nothing else in the app names a font.
 */
